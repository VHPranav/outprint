import * as React from "react";
import { cn } from "@/lib/utils";

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { interactive?: boolean }
>(({ className, interactive, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-xl border border-[#E5E5E5] bg-white text-neutral-900 shadow-subtle transition-all duration-200",
      interactive &&
        "hover:border-neutral-300 hover:shadow-card-hover cursor-pointer",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

